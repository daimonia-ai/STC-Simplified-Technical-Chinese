// Human-readable guidance shared by CLI and agent consumers.
const RULES = {
  G3: ['写法可以更直接', '删掉重复或绕远的表达，保留动作和对象。'],
  G4: ['动作藏在套话里', '删掉虚动词，直接写动作，例如把“进行检查”改为“检查”。'],
  G5: ['事实或数量不清楚', '删掉后意思不变时直接删掉；需要具体信息时写明对象、数量或变化。'],
  G6: ['套话没有说明具体事情', '删掉后意思不变时直接删掉；否则写出具体动作、对象和结果。'],
  G7: ['口号代替了事实', '删掉口号句式，直接写已知的事实；需要对比时分成两句。'],
  G12: ['一句话包含的信息太多', '按动作或判断拆句；先写结论，再写依据。'],
  G17: ['中文引号需要统一', '横排中文使用全角双引号“”；嵌套引用使用单引号‘’。'],
  G19: ['中文与英文或数字之间缺少空格', '在中文与英文、数字之间加一个空格。'],
  G20: ['这句话可能不服务当前读者', '核对是否帮助当前读者理解、判断或操作。删掉无关排除、制作说明和自证；必要边界保留并记录具体理由。'],
  C3: ['回复语气过强', '按句意改用句号或问号。'],
  D1: ['读者不知道主语是谁', '写出团队、公司或人名。主语是作者本人或作者所在团队时，可省略主语。'],
  W1: ['界面文字的指代不明确', '改成具体的角色、产品或对象名称；名称不明时标成“【待补：名称】”。'],
  W2: ['读者称呼需要统一', '称读者为“你 / your”，也可省略代词，例如将“我的订单”改为“你的订单”或“订单”。引用用户原话时保留引号。'],
  W10: ['同一处界面混用了读者口吻', '标题、按钮、菜单和说明统一称读者为“你 / your”。说明文字可省略代词，例如“还没有订单”。'],
  I1: ['要求的强度不明确', '要求用“必须、不得”，推荐用“宜、不宜”，允许用“可、不必”。'],
  I2: ['同一句混用了要求和推荐', '确定强度：要求写“必须”，推荐写“宜”。'],
};

export function issueAdvice(rule, message, entry, match) {
  const [title, fallback] = RULES[rule] ?? ['写法需要调整', message];
  let suggestion = entry?.use ?? fallback;
  if (rule === 'G4') suggestion = `删掉“${match}”，直接写后面的动作。`;
  if (rule === 'G5') suggestion += '。缺少的信息影响理解或操作时，写“【待补：具体事实】”；不得编造数字';
  if (rule === 'D1' || rule === 'W1') suggestion = fallback;
  return { title, reason: entry?.why ?? message, suggestion };
}
