#!/usr/bin/env node
// Generate the browser entry from the maintained rules and dictionary.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, posix, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const REPO = 'https://github.com/daimonia-ai/STC-Simplified-Technical-Chinese';
const RAW = 'https://raw.githubusercontent.com/daimonia-ai/STC-Simplified-Technical-Chinese/main/WEB.md';

const SOURCES = [
  ['rules/README.md', 'rule-index', '规则导航'],
  ['rules/for-all.md', 'for-all', '通用规则'],
  ['rules/for-chat.md', 'for-chat', '聊天场景'],
  ['rules/for-document.md', 'for-document', '文档场景'],
  ['rules/for-web-dev.md', 'for-web-dev', '界面场景'],
  ['rules/for-instruction-writing.md', 'for-instruction-writing', '规则编写场景'],
  ['dictionary/README.md', 'dictionary-guide', '词表说明'],
  ['dictionary/avoid.yaml', 'avoid-words', '不推荐写法词表'],
  ['dictionary/recommended.yaml', 'recommended-words', '推荐词表'],
  ['dictionary/terms.example.yaml', 'project-terms', '项目术语表模板'],
];
const anchors = new Map(SOURCES.map(([file, id]) => [file, id]));

function section(text, title, level = 2) {
  const heading = `${'#'.repeat(level)} ${title}\n`;
  const start = text.indexOf(heading);
  if (start < 0) throw new Error(`Missing SKILL.md section: ${title}`);
  const body = start + heading.length;
  const next = text.slice(body).search(new RegExp(`\\n#{1,${level}} `));
  const end = next < 0 ? -1 : body + next;
  return text.slice(body, end < 0 ? undefined : end).trim();
}

function markdown(text, file) {
  let fenced = false;
  // Headings are nested under the source section. Examples stay unchanged.
  return text.split('\n').map((line) => {
    if (/^\s*```/.test(line)) { fenced = !fenced; return line; }
    if (fenced) return line;
    return line.replace(/^(#{2,5}) /, '#$1 ').replace(/\]\(([^)\s]+)\)/g, (match, target) => {
      if (/^(?:[a-z]+:|#|\/)/i.test(target)) return match;
      const [path, fragment] = target.split('#');
      const relative = posix.normalize(posix.join(posix.dirname(file), path));
      if (anchors.has(relative)) return `](#${fragment || anchors.get(relative)})`;
      const type = path.endsWith('/') ? 'tree' : 'blob';
      return `](${REPO}/${type}/main/${relative}${fragment ? `#${fragment}` : ''})`;
    });
  }).join('\n');
}

export function renderWeb(root = ROOT) {
  const read = (file) => readFileSync(join(root, file), 'utf8').replace(/\r\n/g, '\n');
  const guide = read('snippets/web-onboarding.md');
  const skill = read('SKILL.md');
  const contents = SOURCES.map(([file, id, title]) => ({ file, id, title, text: read(file) }));
  const hash = createHash('sha256').update(guide).update(skill);
  for (const { file, text } of contents) hash.update(file).update('\0').update(text);
  const sourceHash = hash.digest('hex');
  const links = contents.map(({ id, title }) => `- [${title}](#${id})`).join('\n');
  const output = [
    '# STC · 简明技术性中文',
    'Simplified Technical Chinese',
    `[GitHub 页面](${REPO}/blob/main/WEB.md) · [纯文本链接](${RAW})`,
    '<!-- Generated by npm run build:web. Edit the source files, not WEB.md. -->',
    `<!-- Source SHA-256: ${sourceHash} -->`,
    '本页包含网页接入引导、写作流程、全部规则和词表。聊天 AI 可以直接读取本页。',
    markdown(guide, 'snippets/web-onboarding.md').replace(/^# /, '## '),
    '## 规则与词表目录',
    links,
    '## 默认表达方式',
    markdown(section(skill, '默认表达方式'), 'SKILL.md'),
    '## 写作与审阅流程',
    markdown(section(skill, '第三步：按用法处理'), 'SKILL.md'),
    '## 语义复核',
    markdown(section(section(skill, '第四步：自查'), '语义复核', 3), 'SKILL.md'),
    '## 不改动的内容',
    markdown(section(skill, '不改动的内容'), 'SKILL.md'),
  ];
  for (const { file, id, title, text } of contents) {
    output.push(`<a id="${id}"></a>\n\n## ${title}`);
    if (file.endsWith('.yaml')) {
      output.push(`\`\`\`yaml\n${text.trimEnd()}\n\`\`\``);
    } else {
      output.push(markdown(text.replace(/^# [^\n]+\n+/, ''), file).trim());
    }
  }
  output.push(
    '## 来源与许可',
    `由 [Daimonia](${REPO}) 维护。规则与词表采用 [CC BY 4.0](${REPO}/blob/main/LICENSE)，工具代码采用 [MIT](${REPO}/blob/main/LICENSE-CODE)。`,
    '## 全文结束',
    '`STC_WEB_END`',
  );
  return `${output.join('\n\n')}\n`;
}

export function writeWeb(root = ROOT, { check = false } = {}) {
  const path = join(root, 'WEB.md');
  const expected = renderWeb(root);
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== expected) {
      throw new Error('WEB.md is out of date. Run npm run build:web.');
    }
  } else {
    writeFileSync(path, expected);
  }
  return path;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
    console.error('Usage: node tools/build-web.mjs [--check]');
    process.exitCode = 2;
  } else {
    try {
      writeWeb(ROOT, { check: args.includes('--check') });
      console.log(args.includes('--check') ? 'WEB.md is current.' : 'Generated WEB.md.');
    } catch (error) {
      console.error(error.message);
      process.exitCode = 1;
    }
  }
}
