// Keep UI rules and their action dictionary in one readable local resource.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const TARGET = 'rules/web-dev-reference.md';

export function renderUiReference(root = ROOT) {
  const read = (path) => readFileSync(join(root, path), 'utf8').replace(/\r\n/g, '\n');
  const rules = read('rules/for-web-dev.md').replace(
    '[`recommended.yaml`](../dictionary/recommended.yaml)',
    '[推荐词表](#recommended-words)',
  );
  const general = read('rules/for-all.md');
  const headings = [...general.matchAll(/^### G20[ \t][^\n]*$/gm)];
  if (headings.length !== 1) throw new Error('Missing G20 or duplicate G20 in rules/for-all.md');
  const tail = general.slice(headings[0].index);
  const nextHeading = tail.slice(headings[0][0].length).search(/\n#{1,3}[ \t]/);
  const end = nextHeading < 0 ? undefined : headings[0][0].length + nextHeading;
  const g20 = tail.slice(0, end).trimEnd();
  if (!g20.slice(headings[0][0].length).trim()) throw new Error('Missing G20 body in rules/for-all.md');
  const dictionary = read('dictionary/recommended.yaml');
  return [
    '<!-- Generated by tools/build-ui-reference.mjs. Edit the canonical rules and dictionary. -->',
    rules.trimEnd(),
    '## 共享检查规则',
    g20,
    '<a id="recommended-words"></a>\n\n## 推荐词表',
    `\`\`\`yaml\n${dictionary.trimEnd()}\n\`\`\``,
  ].join('\n\n') + '\n';
}

export function writeUiReference(root = ROOT, { check = false } = {}) {
  const path = join(root, TARGET);
  const expected = renderUiReference(root);
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== expected) {
      throw new Error('UI reference is out of date. Run npm run build:web.');
    }
  } else writeFileSync(path, expected);
  return path;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length && args[0] !== '--check')) {
    console.error('Usage: node tools/build-ui-reference.mjs [--check]');
    process.exitCode = 2;
  } else {
    try { writeUiReference(ROOT, { check: args.includes('--check') }); }
    catch (error) { console.error(error.message); process.exitCode = 1; }
  }
}
